// Generates supabase/seed.sql from supabase/seed/data/*.ts.
// Run: pnpm db:seed:generate

import { writeFileSync } from "node:fs";
import { slugify } from "../src/lib/slug.ts";
import {
  municipalities,
  regions,
  settlements,
} from "../supabase/seed/data/cities.ts";
import { serviceContent } from "../supabase/seed/data/service-content.ts";
import { serviceGroups } from "../supabase/seed/data/services.ts";

const OUT = new URL("../supabase/seed.sql", import.meta.url);

// Top-level routes that a "{service}-{city}" slug must never shadow.
const RESERVED = [
  "usluge",
  "gradovi",
  "cijene",
  "statistika",
  "za-biznise",
  "kako-funkcionise",
  "pomoc",
  "bezbjednost",
  "o-nama",
  "kontakt",
  "uslovi",
  "uslovi-placanja",
  "privatnost",
  "kolacici",
  "prijava",
  "moj-nalog",
  "panel",
  "admin",
  "b",
  "services",
  "cities",
  "prices",
  "statistics",
  "for-business",
  "uslugi",
  "goroda",
  "ceny",
  "dlya-biznesa",
  "login",
  "pretraga",
  "kako-rangiramo",
  "how-we-rank",
  "kak-my-ranzhiruem",
  "search",
  "poisk",
  "vhod",
  "my-account",
  "moy-akkaunt",
  "api",
];

const q = (v: string | null | undefined) =>
  v == null ? "null" : `'${v.replace(/'/g, "''")}'`;
const n = (v: number | null | undefined) => (v == null ? "null" : String(v));

const errors: string[] = [];

// --- Cities -----------------------------------------------------------------

const cities = [...municipalities, ...settlements].map((c) => ({
  ...c,
  slug: c.slug ?? slugify(c.me),
}));

const citySlugs = new Set<string>();
for (const c of cities) {
  if (citySlugs.has(c.slug)) errors.push(`Duplicate city slug: ${c.slug}`);
  citySlugs.add(c.slug);
}
for (const c of settlements) {
  if (!municipalities.some((m) => slugify(m.me) === c.parent)) {
    errors.push(`Unknown parent "${c.parent}" for ${c.me}`);
  }
}

// --- Services ---------------------------------------------------------------

type Locale = "me" | "en" | "ru";
const locales: Locale[] = ["me", "en", "ru"];

const services = serviceGroups.flatMap((g) =>
  g.services.map(([me, en, ru, { slug, ...o } = {}], i) => ({
    ...o,
    group: g.slug,
    sort: i,
    name: { me, en, ru },
    slug: {
      me: slug?.me ?? slugify(me),
      en: slug?.en ?? slugify(en.replace(/&/g, "and")),
      ru: slug?.ru ?? slugify(ru),
    },
  })),
);

for (const locale of locales) {
  const seen = new Map<string, string>();
  for (const s of services) {
    const slug = s.slug[locale];
    if (!slug) errors.push(`Empty ${locale} slug for ${s.name.me}`);
    if (seen.has(slug))
      errors.push(
        `Duplicate ${locale} slug "${slug}": ${seen.get(slug)} / ${s.name.me}`,
      );
    seen.set(slug, s.name.me);
  }

  // "{service}-{city}" must map back to exactly one pair.
  const combos = new Map<string, string>();
  for (const s of services) {
    for (const c of cities) {
      const combo = `${s.slug[locale]}-${c.slug}`;
      const pair = `${s.slug[locale]} + ${c.slug}`;
      if (combos.has(combo))
        errors.push(
          `Ambiguous ${locale} URL /${combo}: ${combos.get(combo)} vs ${pair}`,
        );
      combos.set(combo, pair);
      if (RESERVED.includes(combo))
        errors.push(`URL /${combo} shadows a reserved route`);
    }
  }
}

if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

// --- SQL --------------------------------------------------------------------

const lines: string[] = [
  "-- Generated by scripts/generate-seed.ts. Do not edit by hand.",
  "",
  "insert into public.regions (slug, name_me, name_en, name_ru, sort_order) values",
  regions
    .map((r, i) => `  (${q(r.slug)}, ${q(r.me)}, ${q(r.en)}, ${q(r.ru)}, ${i})`)
    .join(",\n") + "\non conflict (slug) do nothing;",
  "",
];

const cityValues = (list: typeof cities) =>
  list
    .map(
      (c) =>
        `  (${q(c.slug)}, ${q(c.me)}, ${q(c.en)}, ${q(c.ru)}, ${q(c.locative)}, ${q(c.region)}, ${q(c.parent)}, ${n(c.lat)}, ${n(c.lng)}, ${n(c.population)})`,
    )
    .join(",\n");

const cityInsert = (list: typeof cities) => [
  "insert into public.cities (slug, name_me, name_en, name_ru, name_locative_me, region_id, parent_city_id, lat, lng, population)",
  "select v.slug, v.name_me, v.name_en, v.name_ru, v.loc, r.id, p.id, v.lat::float8, v.lng::float8, v.pop::integer",
  "from (values",
  cityValues(list),
  ") as v(slug, name_me, name_en, name_ru, loc, region, parent, lat, lng, pop)",
  "join public.regions r on r.slug = v.region",
  "left join public.cities p on p.slug = v.parent",
  "on conflict (slug) do nothing;",
  "",
];

// Municipalities first so settlements can resolve their parent.
lines.push(...cityInsert(cities.filter((c) => !c.parent)));
lines.push(...cityInsert(cities.filter((c) => c.parent)));

lines.push(
  "insert into public.service_groups (slug, name_me, name_en, name_ru, icon, sort_order) values",
  serviceGroups
    .map(
      (g, i) =>
        `  (${q(g.slug)}, ${q(g.me)}, ${q(g.en)}, ${q(g.ru)}, ${q(g.icon)}, ${i})`,
    )
    .join(",\n") + "\non conflict (slug) do nothing;",
  "",
  "insert into public.services (group_id, slug_me, slug_en, slug_ru, name_me, name_en, name_ru, plural_gen_me, schema_type, price_unit_default, offers_online, sort_order)",
  "select g.id, v.slug_me, v.slug_en, v.slug_ru, v.name_me, v.name_en, v.name_ru, v.gen, v.schema_type, v.unit::public.price_unit, v.online, v.sort",
  "from (values",
  services
    .map(
      (s) =>
        `  (${q(s.group)}, ${q(s.slug.me)}, ${q(s.slug.en)}, ${q(s.slug.ru)}, ${q(s.name.me)}, ${q(s.name.en)}, ${q(s.name.ru)}, ${q(s.gen)}, ${q(s.schema)}, ${q(s.unit ?? "job")}, ${s.online ? "true" : "false"}, ${s.sort})`,
    )
    .join(",\n"),
  ") as v(grp, slug_me, slug_en, slug_ru, name_me, name_en, name_ru, gen, schema_type, unit, online, sort)",
  "join public.service_groups g on g.slug = v.grp",
  "on conflict (slug_me) do nothing;",
  "",
);

// Hand-written content (update, so re-running the seed refreshes it).
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
for (const [slug, c] of Object.entries(serviceContent)) {
  if (!services.some((s) => s.slug.me === slug))
    errors.push(`Content for unknown service "${slug}"`);
  lines.push(
    `update public.services set description_me = ${q(c.me.description)}, description_en = ${q(c.en.description)}, description_ru = ${q(c.ru.description)}, faq_me = ${json(c.me.faq)}, faq_en = ${json(c.en.faq)}, faq_ru = ${json(c.ru.faq)}, tips_me = ${json(c.me.tips)}, tips_en = ${json(c.en.tips)}, tips_ru = ${json(c.ru.tips)} where slug_me = ${q(slug)};`,
  );
}
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

writeFileSync(OUT, lines.join("\n"));
console.log(
  `seed.sql: ${regions.length} regions, ${cities.length} cities, ${serviceGroups.length} groups, ${services.length} services, content for ${Object.keys(serviceContent).length}`,
);
